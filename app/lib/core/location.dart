/// The supported city nearest to a position, with its great-circle distance in kilometres.
(City, double) nearestCity(double lat, double lon) {
  double km(City c) {
    const r = 6371.0;
    double rad(double d) => d * math.pi / 180;
    final dLat = rad(c.lat - lat), dLon = rad(c.lon - lon);
    final a =
        math.pow(math.sin(dLat / 2), 2) + math.cos(rad(lat)) * math.cos(rad(c.lat)) * math.pow(math.sin(dLon / 2), 2);
    return 2 * r * math.asin(math.sqrt(a));
  }

  var best = cities.first;
  var bestKm = km(best);
  for (final c in cities.skip(1)) {
    final d = km(c);
    if (d < bestKm) (best, bestKm) = (c, d);
  }
  return (best, bestKm);
}
